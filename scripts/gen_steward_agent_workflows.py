#!/usr/bin/env python3
"""Generate the per-engine Gaia Steward agent workflows (gh-aw sources).

The agent body, tools and safe outputs live once in
.github/workflows/shared/steward-{build,verify}.md. Each engine gets a thin
wrapper that carries only its `engine:` and the dispatch inputs (gh-aw reads
`on:` from the compiled workflow, not from an import). Run with --check to
verify the wrappers are current; compile afterwards with a RELEASE build of gh-aw:
`gh aw compile --action-mode action --action-tag vX.Y.Z` (a tag that exists in github/gh-aw-actions; build gh-aw at that same tag). A dev build emits local
`./actions/setup` references that fail on a runner (tests/steward guards this).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ENGINES = {
    "copilot": "engine: copilot",
    "claude": "engine: claude",
    "codex": "engine:\n  id: codex\n  model: gpt-5",
    "pi": "engine: pi",
}

# Engines that authenticate through the repository's Copilot entitlement (no API key).
COPILOTAUTH = ("copilot", "pi")

INPUTS = {
    "build": (
        ("dispatch-id", "Steward dispatch id (for the receipt)"),
        ("base", "Integration branch the change is based on"),
        ("branch", "Branch the change is pushed to (steward/b/...)"),
        ("prompt", "The steward builder prompt, verbatim"),
    ),
    "verify": (
        ("dispatch-id", "Steward dispatch id (for the receipt)"),
        ("prompt", "The steward verifier prompt, verbatim"),
    ),
}


def render(role: str, engine: str) -> str:
    lines = [
        "---",
        f"description: Gaia Steward {role} agent on the {engine} engine (generated by scripts/gen_steward_agent_workflows.py)",
        "on:",
        "  workflow_dispatch:",
        "    inputs:",
    ]
    for name, text in INPUTS[role]:
        lines += [f"      {name}:", f'        description: "{text}"', "        required: true", "        type: string"]
    perms = ["permissions:", "  contents: read", "  actions: read"] + (["  copilot-requests: write"] if engine in COPILOTAUTH else [])
    lines += perms + ["concurrency:", "  job-discriminator: ${{ github.event.inputs.dispatch-id }}", "timeout-minutes: 45", ENGINES[engine], "imports:", f"  - shared/steward-{role}.md", "---", "", f"Run the Gaia Steward {role} task defined in the imported shared workflow.", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when a wrapper is stale")
    parser.add_argument("--dir", default=".github/workflows")
    args = parser.parse_args()
    root = Path(args.dir)
    stale = []
    for role in INPUTS:
        for engine in ENGINES:
            path = root / f"steward-{role}-{engine}.md"
            text = render(role, engine)
            if path.exists() and path.read_text(encoding="utf-8") == text:
                continue
            stale.append(str(path))
            if not args.check:
                path.write_text(text, encoding="utf-8")
    if stale and args.check:
        print("stale: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
