"""GitHub receipts: what Steward picked up, what it verified, and what finally happened.

Every receipt starts with a hidden marker, ``<!-- gaia-steward:pr-receipt kind=... pr=N head=SHA12 run=ID -->``.
The marker is the idempotency key: a resumed run looks for it in the PR's comments (trusted authors only, so a
stranger cannot suppress a receipt by pasting one) and never posts a second. A head SHA change makes every earlier
verification receipt stale, because the marker names the head it vouched for.
"""

from __future__ import annotations

import re
from typing import Any, Mapping, Sequence

from gaia_cli.steward.prmaintenance import advice

# Markers are located with str.find and bounded slices, never a backtracking pattern, so a hostile comment costs linear time.
OPEN = "<!--"
NAME = "gaia-steward:pr-receipt"
CLOSE = "-->"
MAXMARKER = 300
TOKEN = re.compile(r"([a-z]{1,16})=([A-Za-z0-9._:/-]{1,80})")
KINDS = ("pickup", "verification", "merged", "closed", "founder")
TRUSTED = {"OWNER", "MEMBER", "COLLABORATOR"}
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
BOTTOMLINE = {
    "pickup": "Gaia Steward · PR Pickup", "verification": "Gaia Steward · Verification PASS", "merged": "Gaia Steward · MERGED",
    "closed": "Gaia Steward · CLOSED WITHOUT MERGE", "founder": "Gaia Steward · Founder Decision Required",
}


def marker(kind: str, number: int, head: str, runId: str) -> str:
    if kind not in KINDS:
        raise ValueError(f"unknown receipt kind {kind!r}")
    return f"<!-- gaia-steward:pr-receipt kind={kind} pr={number} head={head[:12]} run={runId} -->"


def parseMarkers(body: str) -> list[dict[str, str]]:
    found: list[dict[str, str]] = []
    text = (body or "")[:65536]
    cursor = 0
    while True:
        at = text.find(NAME, cursor)
        if at < 0:
            break
        cursor = at + len(NAME)
        if "".join(text[max(0, at - 16):at].split())[-len(OPEN):] != OPEN:
            continue
        end = text.find(CLOSE, cursor, cursor + MAXMARKER + len(CLOSE))
        if end < 0:
            continue
        pairs: dict[str, str] = {}
        for token in text[cursor:end].split():
            parsed = TOKEN.fullmatch(token)
            if parsed is None:
                pairs = {}
                break
            pairs[parsed.group(1)] = parsed.group(2)
        if pairs:
            found.append(pairs)
        cursor = end + len(CLOSE)
    return found


def findReceipt(comments: Sequence[Mapping[str, Any]], kind: str, number: int, head12: str | None = None) -> Mapping[str, Any] | None:
    """The first trusted comment carrying this receipt's marker, or ``None``."""

    for comment in comments:
        if comment.get("authorAssociation") not in TRUSTED:
            continue
        for pairs in parseMarkers(str(comment.get("body") or "")):
            if pairs.get("kind") == kind and pairs.get("pr") == str(number) and (head12 is None or pairs.get("head") == head12):
                return comment
    return None


def lines(title: str, rows: Sequence[tuple[str, str]], tail: str = "") -> str:
    body = "\n".join(f"{key}: {value}  " for key, value in rows)
    return f"### {title}\n\n{body}\n{tail}"


def pickup(*, number: int, head: str, runId: str, producer: str, authority: str, baseRef: str, baseSha: str, action: str) -> str:
    return "\n".join([marker("pickup", number, head, runId), lines(BOTTOMLINE["pickup"], [
        ("Run", runId), ("Producer", producer), ("Classification", f"Class {authority}"), ("Head SHA", head),
        ("Base", f"{baseRef} @ {baseSha}"), ("Assigned action", action), ("Status", "IN PROGRESS")])]) + FOOTER


def verification(*, number: int, head: str, runId: str, verifier: str, gates: Mapping[str, str], reconciliation: str,
                 evidence: Sequence[str]) -> str:
    rows = [("Run", runId), ("Verified head", head), ("Independent verifier", verifier)]
    rows += [(label, gates[key]) for label, key in (("Provenance", "provenance"), ("Scope", "scope"), ("CI", "ci"),
                                                    ("Policy", "policy"), ("Required reviews", "reviews"))]
    rows += [("Reconciliation", reconciliation)]
    tail = "\nDisposition: MERGE ELIGIBLE\n\nEvidence:\n" + "\n".join(f"- {item}" for item in evidence)
    return "\n".join([marker("verification", number, head, runId), lines(BOTTOMLINE["verification"], rows, tail)]) + FOOTER


def merged(*, number: int, head: str, runId: str, url: str, destination: str, mergeCommit: str, method: str, postMerge: str) -> str:
    return "\n".join([marker("merged", number, head, runId), lines(BOTTOMLINE["merged"], [
        ("PR", url), ("Destination", destination), ("Verified head", head), ("Merge commit", mergeCommit),
        ("Merge method", method), ("Steward run", runId), ("Post-merge verification", postMerge)],
        "\nFinal disposition: MERGED")]) + FOOTER


def closed(*, number: int, head: str, runId: str, url: str, reason: str, replacement: str, verifier: str) -> str:
    return "\n".join([marker("closed", number, head, runId), lines(BOTTOMLINE["closed"], [
        ("PR", url), ("Reason", reason), ("Replacement", replacement),
        ("Independent verification", f"PASS ({verifier})"), ("Steward run", runId)],
        "\nFinal disposition: CLOSED")]) + FOOTER


def founder(*, number: int, head: str, runId: str, authority: str, state: str, evidence: Sequence[str], question: str,
            gates: Sequence[str] = ()) -> str:
    """The founder card. Its two recommendation paragraphs come from ``advice``, the same source the desk renders.

    ``gates`` is the list of gate names the pull request carries; only names in ``advice``'s fixed set shape the text, so
    nothing a pull request controls reaches either paragraph. There is no free-text recommendation argument on purpose: a
    hand-written one is how the receipt and the desk came to disagree.
    """

    procedural, substantive = advice.pair(gates)
    rows = [("Classification", f"Class {authority}"), ("Current state", state)]
    tail = ("\nEvidence:\n" + "\n".join(f"- {item}" for item in evidence)
            + f"\n\nDecision required: {question}"
            + f"\n\n{advice.PROCEDURAL_LABEL}: {procedural}"
            + f"\n\n{advice.SUBSTANTIVE_LABEL}: {substantive}"
            + "\n\nSteward will not merge or close this pull request.")
    return "\n".join([marker("founder", number, head, runId), lines(BOTTOMLINE["founder"], rows, tail)]) + FOOTER
