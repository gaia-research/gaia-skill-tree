def git(root: Path, *args: str) -> None:
    subprocess.run(
        ["git", "-c", "user.name=t", "-c", "user.email=t@t", "-c", "commit.gpgsign=false", *args],
        cwd=root,
        check=True,
        capture_output=True,
    )


def test_baseline_growth_against_base_ref_fails(tmp_path, capsys):
    root = write_repo(tmp_path, {"a.yml": TWO_JOBS}, [(wf("a.yml"), "build")])
    git(root, "init", "-q", "-b", "main")
    git(root, "add", "-A")
    git(root, "commit", "-q", "-m", "base")
    # Someone hides the new job by adding it to the baseline instead of a timeout.
    write_repo(root, {}, [(wf("a.yml"), "build"), (wf("a.yml"), "test")])
    assert main(["--base-ref", "main"], repo_root=root) == 1
    assert "[GROWN] .github/workflows/a.yml: job test" in capsys.readouterr().err
    # Without the base comparison the hidden job would pass: the growth check is load-bearing.
    assert main([], repo_root=root) == 0


