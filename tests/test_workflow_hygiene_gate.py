"""Tests for scripts/check_workflow_hygiene.py (missing-timeout ratchet)."""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

import pytest
import yaml

from scripts.check_workflow_hygiene import (
    BASELINE_RELATIVE,
    REPO_ROOT,
    collect,
    evaluate,
    load_baseline,
    main,
    render_baseline,
)

TIMED = "name: ok\non: push\npermissions: {}\njobs:\n  build:\n    runs-on: ubuntu-latest\n    timeout-minutes: 5\n    steps: []\n"
UNTIMED = "name: bad\non: push\npermissions: {}\njobs:\n  build:\n    runs-on: ubuntu-latest\n    steps: []\n"
TWO_JOBS = (
    "name: two\non: push\npermissions: {}\njobs:\n"
    "  build:\n    runs-on: ubuntu-latest\n    steps: []\n"
    "  test:\n    runs-on: ubuntu-latest\n    steps: []\n"
)
REUSABLE = "name: call\non: push\npermissions: {}\njobs:\n  call:\n    uses: ./.github/workflows/x.yml\n"


def write_repo(root: Path, workflows: dict[str, str], baseline: list[tuple[str, str]] | None) -> Path:
    folder = root / ".github" / "workflows"
    folder.mkdir(parents=True, exist_ok=True)
    for name, text in workflows.items():
        (folder / name).write_text(text, encoding="utf-8")
    if baseline is not None:
        path = root / BASELINE_RELATIVE
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render_baseline(baseline), encoding="utf-8")
    return root


def wf(name: str) -> str:
    return f".github/workflows/{name}"


def test_baselined_open_job_passes(tmp_path, capsys):
    root = write_repo(tmp_path, {"a.yml": UNTIMED, "b.yml": TIMED}, [(wf("a.yml"), "build")])
    assert main([], repo_root=root) == 0
    assert "PASSED" in capsys.readouterr().out


def test_new_job_in_existing_workflow_fails(tmp_path, capsys):
    root = write_repo(tmp_path, {"a.yml": TWO_JOBS}, [(wf("a.yml"), "build")])
    assert main([], repo_root=root) == 1
    err = capsys.readouterr().err
    assert "[BLOCKING] .github/workflows/a.yml: job test has no timeout-minutes" in err


def test_new_workflow_without_timeout_fails(tmp_path, capsys):
    root = write_repo(tmp_path, {"a.yml": UNTIMED, "new.yaml": UNTIMED}, [(wf("a.yml"), "build")])
    assert main([], repo_root=root) == 1
    assert "[BLOCKING] .github/workflows/new.yaml: job build" in capsys.readouterr().err


def test_new_workflow_with_timeouts_passes(tmp_path):
    root = write_repo(tmp_path, {"a.yml": UNTIMED, "new.yml": TIMED}, [(wf("a.yml"), "build")])
    assert main([], repo_root=root) == 0


def test_reusable_workflow_call_is_not_flagged(tmp_path):
    # Same rule as the sensor: a `uses:` call job cannot carry timeout-minutes.
    root = write_repo(tmp_path, {"call.yml": REUSABLE}, [])
    assert main([], repo_root=root) == 0


def test_repaired_job_is_stale_and_fails_until_pruned(tmp_path, capsys):
    root = write_repo(tmp_path, {"a.yml": TIMED}, [(wf("a.yml"), "build")])
    assert main([], repo_root=root) == 1
    assert "[STALE] .github/workflows/a.yml: job build" in capsys.readouterr().err

    # Warn mode (PRs into dev/*) reports but does not fail.
    assert main(["--stale", "warn"], repo_root=root) == 0
    assert "[STALE-WARN]" in capsys.readouterr().out

    assert main(["--prune-baseline"], repo_root=root) == 0
    assert load_baseline(root / BASELINE_RELATIVE) == set()
    assert main([], repo_root=root) == 0


def test_stale_entry_for_deleted_workflow(tmp_path):
    root = write_repo(tmp_path, {"a.yml": UNTIMED}, [(wf("a.yml"), "build"), (wf("gone.yml"), "build")])
    assert evaluate(*collect(root)[:1], load_baseline(root / BASELINE_RELATIVE))["stale"] == [(wf("gone.yml"), "build")]
    assert main([], repo_root=root) == 1


def test_prune_never_adds_entries(tmp_path):
    root = write_repo(tmp_path, {"a.yml": TWO_JOBS}, [(wf("a.yml"), "build")])
    assert main(["--prune-baseline"], repo_root=root) == 0
    assert load_baseline(root / BASELINE_RELATIVE) == {(wf("a.yml"), "build")}
    assert main([], repo_root=root) == 1  # `test` is still new


def test_lock_files_are_excluded_but_reported(tmp_path, capsys):
    root = write_repo(tmp_path, {"agent.lock.yml": TWO_JOBS, "a.yml": TIMED}, [])
    hand, generated, errors = collect(root)
    assert hand == set() and errors == []
    assert generated == {(wf("agent.lock.yml"), "build"), (wf("agent.lock.yml"), "test")}
    assert main([], repo_root=root) == 0
    out = capsys.readouterr().out
    assert "[EXCLUDED] .github/workflows/agent.lock.yml: job build" in out
    assert "Generated lock (excluded): 2 jobs in 1 files" in out


def test_gh_aw_banner_file_is_excluded(tmp_path):
    banner = "# This file was automatically generated by gh-aw. DO NOT EDIT.\n" + UNTIMED
    root = write_repo(tmp_path, {"compiled.yml": banner}, [])
    hand, generated, _ = collect(root)
    assert hand == set() and generated == {(wf("compiled.yml"), "build")}


def test_baseline_entry_for_lock_file_is_rejected(tmp_path, capsys):
    root = write_repo(tmp_path, {"agent.lock.yml": UNTIMED}, None)
    path = root / BASELINE_RELATIVE
    path.parent.mkdir(parents=True)
    data = json.loads(render_baseline([]))
    data["entries"] = [{"workflow": wf("agent.lock.yml"), "job": "build"}]
    path.write_text(json.dumps(data), encoding="utf-8")
    assert main([], repo_root=root) == 2
    assert "generated lock file" in capsys.readouterr().err


@pytest.mark.parametrize(
    "entries",
    [
        [{"workflow": wf("a.yml"), "job": "build"}, {"workflow": wf("a.yml"), "job": "build"}],
        [{"workflow": ".github/workflows/shared/a.yml", "job": "build"}],
        [{"workflow": wf("a.yml")}],
        "not-a-list",
    ],
)
def test_malformed_baseline_fails_closed(tmp_path, entries):
    root = write_repo(tmp_path, {"a.yml": UNTIMED}, None)
    path = root / BASELINE_RELATIVE
    path.parent.mkdir(parents=True)
    data = json.loads(render_baseline([]))
    data["entries"] = entries
    path.write_text(json.dumps(data), encoding="utf-8")
    assert main([], repo_root=root) == 2


