def git(root: Path, *args: str) -> None:
    subprocess.run(
        ["git", "-c", "user.name=t", "-c", "user.email=t@t", "-c", "commit.gpgsign=false", *args],
        cwd=root,
        check=True,
        capture_output=True,
    )


def test_baseline_growth_against_base_ref_fails(tmp_path, capsys):
    root = write_repo(tmp_path, {"a.yml": TWO_JOBS}, [(wf("a.yml"), "build")])
    git(root, "init", "-q", "-b", "main")
    git(root, "add", "-A")
    git(root, "commit", "-q", "-m", "base")
    # Someone hides the new job by adding it to the baseline instead of a timeout.
    write_repo(root, {}, [(wf("a.yml"), "build"), (wf("a.yml"), "test")])
    assert main(["--base-ref", "main"], repo_root=root) == 1
    assert "[GROWN] .github/workflows/a.yml: job test" in capsys.readouterr().err
    # Without the base comparison the hidden job would pass: the growth check is load-bearing.
    assert main([], repo_root=root) == 0


def test_base_ref_without_baseline_skips_growth_check(tmp_path, capsys):
    root = write_repo(tmp_path, {"a.yml": UNTIMED}, None)
    git(root, "init", "-q", "-b", "main")
    git(root, "add", "-A")
    git(root, "commit", "-q", "-m", "base")
    write_repo(root, {}, [(wf("a.yml"), "build")])
    assert main(["--base-ref", "main"], repo_root=root) == 0
    assert "has no baseline yet" in capsys.readouterr().out


def test_unresolvable_base_ref_fails_closed(tmp_path):
    root = write_repo(tmp_path, {"a.yml": UNTIMED}, [(wf("a.yml"), "build")])
    git(root, "init", "-q", "-b", "main")
    assert main(["--base-ref", "no-such-ref"], repo_root=root) == 2


def test_committed_baseline_is_valid_and_hand_written_only():
    pairs = load_baseline(REPO_ROOT / BASELINE_RELATIVE)
    assert pairs, "baseline should list the open hand-written set"
    assert not any(w.endswith(".lock.yml") for w, _ in pairs)


def test_guard_workflow_holds_its_own_rule():
    doc = yaml.safe_load((REPO_ROOT / ".github/workflows/workflow-hygiene-guard.yml").read_text(encoding="utf-8"))
    assert doc["permissions"] == {"contents": "read"}
    for job in doc["jobs"].values():
        assert isinstance(job.get("timeout-minutes"), int)
