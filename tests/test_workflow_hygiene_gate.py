def test_committed_baseline_is_valid_and_hand_written_only():
    baseline = load_baseline(REPO_ROOT / BASELINE_RELATIVE)
    assert baseline.entries, "baseline should list the open hand-written set"
    assert not any(w.endswith(".lock.yml") for w, _ in baseline.entries)
    # Exactly the eight known gh-aw locks are pinned, each with its .md source beside it.
    assert len(baseline.pinned) == 8
    for lock in baseline.pinned:
        assert (REPO_ROOT / lock.replace(".lock.yml", ".md")).is_file()


def test_guard_workflow_pins_every_action_to_a_full_sha():
    import re

    text = (REPO_ROOT / ".github/workflows/workflow-hygiene-guard.yml").read_text(encoding="utf-8")
    uses = re.findall(r"^\s*(?:-\s*)?uses:\s*(\S+)(.*)$", text, re.MULTILINE)
    assert uses
    for ref, comment in uses:
        assert re.fullmatch(r"[\w.-]+/[\w.-]+@[0-9a-f]{40}", ref), ref
        assert re.match(r"\s+# v\d", comment), f"{ref} needs a version comment"


def test_guard_workflow_holds_its_own_rule():
    doc = yaml.safe_load((REPO_ROOT / ".github/workflows/workflow-hygiene-guard.yml").read_text(encoding="utf-8"))
    assert doc["permissions"] == {"contents": "read"}
    for job in doc["jobs"].values():
        assert isinstance(job.get("timeout-minutes"), int)


# --- review P1-1: the first baseline is judged against the base's own findings -------


def committed(tmp_path, workflows):
    root = write_repo(tmp_path, workflows, None)
    git(root, "init", "-q", "-b", "main")
    git(root, "add", "-A")
    git(root, "commit", "-q", "-m", "base")
    return root


def test_first_baseline_cannot_adopt_a_new_untimed_job(tmp_path, capsys):
    root = committed(tmp_path, {"old.yml": UNTIMED})
    write_repo(root, {"new.yml": UNTIMED}, [(wf("old.yml"), "build"), (wf("new.yml"), "build")])
    assert main(["--base-ref", "main"], repo_root=root) == 1
    out = capsys.readouterr()
    assert "sensor findings at main (it has no baseline yet)" in out.out
    assert "[GROWN] .github/workflows/new.yml: job build" in out.err
    assert "old.yml" not in out.err


def test_first_baseline_of_existing_findings_passes(tmp_path):
    root = committed(tmp_path, {"old.yml": TWO_JOBS})
    write_repo(root, {}, [(wf("old.yml"), "build"), (wf("old.yml"), "test")])
    assert main(["--base-ref", "main"], repo_root=root) == 0


def test_first_baseline_cannot_pin_a_lock_the_base_did_not_have(tmp_path, capsys):
    root = committed(tmp_path, {"a.yml": TIMED})
    write_repo(root, {"new.lock.yml": BANNER + UNTIMED}, [], pins=(wf("new.lock.yml"),))
    (root / ".github/workflows/new.md").write_text("source\n", encoding="utf-8")
    assert main(["--base-ref", "main"], repo_root=root) == 1
    assert "[GROWN] .github/workflows/new.lock.yml is pinned" in capsys.readouterr().err


def test_first_baseline_may_pin_a_lock_the_base_already_had(tmp_path):
    root = committed(tmp_path, {"agent.lock.yml": BANNER + UNTIMED, "agent.md": "source\n"})
    write_repo(root, {}, [], pins=(wf("agent.lock.yml"),))
    assert main(["--base-ref", "main"], repo_root=root) == 0


def test_a_pin_added_after_the_baseline_exists_is_growth(tmp_path, capsys):
    root = committed(tmp_path, {"a.yml": TIMED})
    write_repo(root, {}, [])
    git(root, "add", "-A")
    git(root, "commit", "-q", "-m", "gate")
    write_repo(root, {"new.lock.yml": BANNER + UNTIMED, "new.md": "source\n"}, [], pins=(wf("new.lock.yml"),))
    assert main(["--base-ref", "main"], repo_root=root) == 1
    assert "[GROWN] .github/workflows/new.lock.yml is pinned" in capsys.readouterr().err
