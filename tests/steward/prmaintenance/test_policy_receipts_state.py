SECTION = yaml.safe_load((h.SOURCE / "founder/steward/POLICY.yaml").read_text())["prMaintenance"]


def test_the_shipped_policy_is_within_every_ceiling_and_never_allows_squash():
    policy = loadPrMaintenancePolicy(SECTION)
    assert policy.mergeMethods == ("merge",) and policy.destinations == ("main",)
    assert policy.maxMergesPerRun <= 5 and policy.maxClosuresPerRun <= 5 and policy.hourlyWriteCap <= 25


@pytest.mark.parametrize("key,value", [("maxMergesPerRun", 6), ("maxClosuresPerRun", 99), ("hourlyWriteCap", 26), ("maxCommentsPerRun", 61),
                                       ("maxCensusAgeSeconds", 10), ("verificationTtlSeconds", 10), ("writesEnabled", "yes"),
                                       ("mergeMethods", ["squash"]), ("mergeMethods", []), ("enabledActions", ["push"]),
                                       ("destinations", ["--force"]), ("destinations", [])])
def test_a_policy_edit_can_lower_a_ceiling_but_never_raise_it_or_widen_the_surface(key, value):
    bad = copy.deepcopy(SECTION)
    bad[key] = value
    with pytest.raises(PrPolicyError):
        loadPrMaintenancePolicy(bad)


def test_unknown_or_missing_keys_fail_loudly_and_an_absent_section_grants_nothing():
    for mutate in (lambda s: s.pop("killSwitch"), lambda s: s.update(extraAuthority=True)):
        bad = copy.deepcopy(SECTION)
        mutate(bad)
        with pytest.raises(PrPolicyError):
            loadPrMaintenancePolicy(bad)
    nothing = loadPrMaintenancePolicy(None)
    assert nothing.writesEnabled is False and not nothing.actionEnabled("merge")


def test_a_switch_edit_alone_never_ratifies_the_route(tmp_path):
    fx = h.makeRepo(tmp_path)
    assert prAuthorityApproved(fx.root) and StewardPolicy.load(fx.root).pr_maintenance.actionEnabled("merge")
    (fx.root / "founder/steward/decisions/steward-pr-maintenance-authority.json").unlink()
    loaded = StewardPolicy.load(fx.root)
    assert loaded.pr_maintenance.writesEnabled is False and not loaded.pr_maintenance.actionEnabled("merge")
    assert loaded.pr_maintenance.maxMergesPerRun == SECTION["maxMergesPerRun"]  # limits stay readable; authority does not


def test_a_malformed_section_disables_only_this_route_not_the_rest_of_the_policy(tmp_path):
    fx = h.makeRepo(tmp_path)
    path = fx.root / "founder/steward/POLICY.yaml"
    data = yaml.safe_load(path.read_text())
    data["prMaintenance"]["maxMergesPerRun"] = 50
    path.write_text(yaml.safe_dump(data))
    loaded = StewardPolicy.load(fx.root)
    assert loaded.pr_maintenance_error and not loaded.pr_maintenance.actionEnabled("merge")
    assert loaded.max_dispatches_per_run == 8  # the rest of the shipped policy still loads


def test_policy_classifies_all_eight_kinds_and_only_the_founder_kind_is_class_c():
    policy = StewardPolicy.load(h.SOURCE)
    kinds = [k for k in policy.authority if k.startswith("routine_pr_")]
    assert len(kinds) == 8
    assert {k for k in kinds if policy.authority[k].value == "C"} == {"routine_pr_founder_decision"}
    with pytest.raises(PolicyError):
        policy.authority_for("routine_pr_unregistered")


